async def assembled_assets(tmp_path,monkeypatch,*,restore_asset_cache=False):
    req,raw=reference_material('Only stable identity from adopted portraits; current Action and voice remain authoritative.')
    author=Author();p=plugin(tmp_path,monkeypatch,author)
    canon=FilmCanon(work=req.canon.work,script=req.canon.script,
        scenes=(CanonScene(scene_id=req.scope.scene_id,scene=req.canon.scene),))
    p.asset_sequence.bind_film(req.scope.work_id,canon,source_ref=ArtifactReference(owner='offline',artifact_ref='fixture-selected-film'))
    req,pending=await resolve(p,req,author)
    assert pending==[req.scope.scene_id]
    current=req.professional_context['assetSequence']['currentAssets']
    assert len(current)==2
    before=[dump_contract(a) for a in p.providers.asset.data.assets]
    if restore_asset_cache:
        for a in current:
            for name in ('design','adoption'):
                # Remove only fixture-local discovery copies, never Service originals.
                pin=a['content']['specializedAsset'][name+'Ref']
                p.asset_sequence.objects._path('objects',pin['fingerprint']).unlink()
    assert (await resolve(p,req,author))[1]==[]
    assert before==[dump_contract(a) for a in p.providers.asset.data.assets]
    monkeypatch.setattr(scope_delivery,'configured',lambda *args:p)
    p,compiler,package,out=await scope_delivery.pipeline(tmp_path,monkeypatch,req,raw,duration=None)
    oldrefs=out[0]['task'].owners.adopted_refs
    core=tuple(r for r in oldrefs if p.creative_versions.resolve(r).kind!=Kind.PROFESSIONAL)
    # Real resolver persistence inserts system-owned assetBindings; model DTO cannot.
    req=req.model_copy(update={'source_refs':core});resolver=ProfessionalDesignResolver(compiler.reader.resolver)
    refs=list(core)
    for ref in oldrefs:
        original=p.creative_versions.resolve(ref)
        if original.kind==Kind.PROFESSIONAL:
            refs.append(resolver.persist(p.creative_versions,req,original.body.model_copy(update={'facts':creative_facts(original.body.facts)}),operation='b4-formal-assets:'+original.body.domain))
    native=NativeCreativeSources(p.creative_versions,tuple(refs),p.execution_references)
    assembled=await ShotAssembler(native,ProfessionalDesignResolver(native)).assemble(req.scope,mode=RunMode.EXPERIMENT,
        policy_ref=ArtifactReference(owner='offline',artifact_ref='unadmitted-preview'))
    assert assembled.package,assembled.validation
    package=assembled.package;compiler.packages.put(package);compiler.reader.resolver=native
    selection=await compiler.reader.operations.select_unit(package,compiler.reader,phase_index=0)
    bindings=asset_reference_candidates(p,NS(refs=tuple(refs)),selection)
    assert len(bindings)==2
    profile=resolve_profile(model='seedance-2-standard',duration_ms=None,resolution='720p',ratio='16:9',
        native_audio=True,mode='reference',policy=compiler.reader.operations.policy)
    task=out[0]['task'].model_copy(update={'unit':selection,'owners':out[0]['task'].owners.model_copy(update={'adopted_refs':tuple(refs)}),
        'profile':profile,'input_mode':'reference','execution_reference_refs':tuple(p.execution_references.register(b) for b in bindings)})
    compiler.references.media_reader=p.providers.media
    return p,compiler,package,task,bindings,req,raw

async def bound_wire(p,compiler,package,task):
    result=await compiler.compile(package.artifact_reference(),task)
    assert result.preparation_ref,compiler.artifacts.diagnostics(result.diagnostics_ref)
    ready=compiler.artifacts.get(result.preparation_ref,GenerationPreparation)
    final=compiler.artifacts.get(ready.final_prompt_ref,FinalPromptArtifact)
    wire=json.loads(json.dumps(TargetHttpTransport.preview(ready,final,ledger=p.ledger)))
    assert not ready.provider_submission_allowed and wire['content'][0]['text']==final.prompt_text
    return ready,final,wire

async def test_formal_adopted_character_assets_reach_final_wire(tmp_path,monkeypatch):
    p,compiler,package,task,bindings,req,raw=await assembled_assets(tmp_path,monkeypatch)
    try:
        ready,final,wire=await bound_wire(p,compiler,package,task)
        assert wire['duration']==-1 and len(wire['content'])==3
        for binding in bindings:
            assert binding.duties[0].purpose in wire['content'][0]['text']
            assert any('media:'+binding.media.media_id+':'+binding.media.content_hash in json.dumps(x) for x in wire['content'][1:])
        assert all(x['role']=='reference_image' for x in wire['content'][1:])
        assert '{Помогите.}' in wire['content'][0]['text']
    finally:await p.aclose()

